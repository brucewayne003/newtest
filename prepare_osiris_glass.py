#!/usr/bin/env python3
"""Prepare a local OsirisKit build for Glass ScannerApp. Python 3.9+, macOS.

Place this file beside the osiris-ios and glass-app folders, then run:
    python3 prepare_osiris_glass.py

No third-party Python packages required. --dry-run makes no changes or downloads.
The real run uses the SDK build script and `glass environment setup -v`, which
can download dependencies and perform the repo's normal environment setup.
It does not commit, push, publish, change branches, or change xcode-select.
"""

import argparse
import datetime as dt
import hashlib
import json
import os
from pathlib import Path
import plistlib
import re
import shlex
import shutil
import signal
import subprocess
import sys
import time
import uuid
import zipfile


MODULES = ("Osiris", "OsirisBarcode", "OsirisCamera")
STATE_DIR = ".osiris-glass-test"
SCRIPT_REL = Path("ci_scripts/xcframework-build.sh")
OSIRIS_JSON = Path("BinaryDependencySpecification/OsirisKit.json")
ZXING_JSON = Path("BinaryDependencySpecification/ZXingCPP.json")
LOCK_REL = Path("Cartfile.resolved")
HEADER_ANCHOR = '  framework_info_plist "${PLATFORM_KEY}" "${FRAMEWORK_DIR}/Info.plist"'
HEADER_BLOCK = '''  # BEGIN LOCAL_OSIRIS_CARTHAGE_HEADERS_V1
  local SDK_NAME
  if [[ "${PLATFORM_KEY}" == "iPhoneOS" ]]; then
    SDK_NAME="iphoneos"
  else
    SDK_NAME="iphonesimulator"
  fi

  local GENERATED_HEADERS_DIR="${SLICE_DIR}/DerivedData/Build/Intermediates.noindex/GeneratedModuleMaps-${SDK_NAME}"
  mkdir -p "${FRAMEWORK_DIR}/Headers"

  for MODULE in "${MODULES[@]}"; do
    local GENERATED_HEADER="${GENERATED_HEADERS_DIR}/${MODULE}-Swift.h"
    if [[ ! -f "${GENERATED_HEADER}" ]]; then
      echo "ERROR: Generated Swift header not found: ${GENERATED_HEADER}" >&2
      exit 1
    fi
    if ! grep -q "Generated by Apple Swift version" "${GENERATED_HEADER}"; then
      echo "ERROR: Swift compiler version missing from ${GENERATED_HEADER}" >&2
      exit 1
    fi
    cp "${GENERATED_HEADER}" "${FRAMEWORK_DIR}/Headers/"
  done
  # END LOCAL_OSIRIS_CARTHAGE_HEADERS_V1

'''


class SetupError(Exception):
    pass


def require(condition, message):
    if not condition:
        raise SetupError(message)


def sha(path):
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def atomic_write(path, data, mode=None):
    """Replace a regular file without following a destination symlink."""
    require(not path.is_symlink(), f"Refusing to replace a symlink: {path}")
    if mode is None:
        mode = (path.stat().st_mode & 0o777) if path.exists() else 0o600
    temporary = path.with_name(path.name + ".tmp-" + uuid.uuid4().hex)
    try:
        with temporary.open("xb") as handle:
            handle.write(data)
        temporary.chmod(mode)
        os.replace(temporary, path)
    finally:
        if temporary.exists():
            temporary.unlink()


def json_bytes(value):
    return (json.dumps(value, indent=2) + "\n").encode()


def read_json(path):
    try:
        result = json.loads(path.read_text())
    except (ValueError, OSError) as exc:
        raise SetupError(f"Cannot read JSON at {path}: {exc}") from exc
    require(isinstance(result, dict), f"Expected a JSON object at {path}")
    return result


def sdk_root(path):
    return (path / SCRIPT_REL).is_file() and (path / "Package.swift").is_file()


def glass_root(path):
    return all((path / rel).is_file() for rel in (
        OSIRIS_JSON, ZXING_JSON, LOCK_REL, Path("Glass.plist"),
        Path("Plugins/Scanner/Scanner.xcodeproj/xcshareddata/xcschemes/ScannerApp.xcscheme"),
    ))


def discover(parent, explicit, predicate, label):
    if explicit:
        path = explicit.expanduser().resolve()
        require(predicate(path), f"Not the expected {label} repo: {path}")
        return path
    candidates = [p.resolve() for p in parent.iterdir()
                  if p.is_dir() and not p.name.startswith(".") and predicate(p)]
    require(len(candidates) == 1,
            f"Expected one {label} repo directly beside this script; found {len(candidates)}. "
            f"Use --{label} /absolute/path/to/repo to select it.")
    return candidates[0]


def patch_script(original):
    require(original.count(HEADER_ANCHOR) == 1,
            "The SDK packaging script has changed: expected header insertion point is missing or ambiguous.")
    required = ('MODULES=(Osiris OsirisBarcode OsirisCamera)',
                'BUILD_DIR="${WORKING_DIR}/build-xcframework"',
                'XCFRAMEWORK_NAME="OsirisKit"')
    require(all(text in original for text in required),
            "Unrecognized SDK packaging script. Stopped rather than rewriting a different build workflow.")
    if "LOCAL_OSIRIS_CARTHAGE_HEADERS_V1" in original:
        require(original.count(HEADER_BLOCK) == 1,
                "The previously inserted header block was edited. Review it before rerunning.")
    elif "Generated Swift header not found:" in original and "${FRAMEWORK_DIR}/Headers" in original:
        # Recognize the exact manual patch supplied earlier in this conversation.
        manual = HEADER_BLOCK.replace("  # BEGIN LOCAL_OSIRIS_CARTHAGE_HEADERS_V1\n", "")
        manual = manual.replace("  # END LOCAL_OSIRIS_CARTHAGE_HEADERS_V1\n", "")
        normalize = lambda value: "\n".join(line.strip() for line in value.splitlines() if line.strip())
        require(normalize(manual) in normalize(original),
                "An existing header-copy change differs from the supported patch. Please review it first.")
    else:
        require("${FRAMEWORK_DIR}/Headers" not in original,
                "This packaging script already handles headers differently. Please review it first.")
        original = original.replace(HEADER_ANCHOR, HEADER_BLOCK + HEADER_ANCHOR)
    if not re.search(r"(?m)^set -o pipefail\s*$", original):
        require(len(re.findall(r"(?m)^set -e\s*$", original)) == 1,
                "Expected exactly one 'set -e' in the packaging script.")
        original = re.sub(r"(?m)^set -e[ \t]*$", "set -e\nset -o pipefail", original, count=1)
    return original


def zxing_spec(sdk):
    text = (sdk / "Package.swift").read_text()
    matches = re.findall(
        r'\.binaryTarget\(\s*name:\s*"ZXingCpp",\s*url:\s*"([^"]+)",\s*'
        r'checksum:\s*"([0-9a-fA-F]{64})"', text)
    require(len(matches) == 1, "Could not identify exactly one remote ZXingCpp target in Package.swift.")
    url, checksum = matches[0]
    require(url.startswith("https://") and url.endswith(".zip"), "Unexpected ZXing artifact URL.")
    return url, checksum.lower()


def change_lock(original, version):
    result = original
    for name in ("OsirisKit", "ZXingCPP"):
        pattern = r'(?m)^(binary[ \t]+"BinaryDependencySpecification/' + name + r'\.json"[ \t]+)"[^"]+"([ \t]*)$'
        result, count = re.subn(pattern, lambda m: m[1] + '"' + version + '"' + m[2], result)
        require(count == 1, f"Expected exactly one {name} entry in Cartfile.resolved; found {count}.")
    return result


class Runner:
    def __init__(self, env, logs=None):
        self.env = env
        self.logs = logs

    def capture(self, args, cwd=None):
        result = subprocess.run(args, cwd=cwd, env=self.env, text=True,
                                stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
        require(result.returncode == 0, f"Command failed: {shlex.join(args)}\n{result.stdout.strip()}")
        return result.stdout.strip()

    def stream(self, args, cwd, name):
        path = self.logs / (name + ".log")
        print(f"\nRunning: {shlex.join(args)}\nFolder: {cwd}\nLog: {path}", flush=True)
        with path.open("w") as log:
            log.write(f"Command: {shlex.join(args)}\nWorking directory: {cwd}\n")
            log.flush()
            process = subprocess.Popen(args, cwd=cwd, env=self.env, text=True,
                                       stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                                       errors="replace", start_new_session=True)
            try:
                for line in process.stdout:
                    print(line, end="", flush=True)
                    log.write(line)
                    log.flush()
                code = process.wait()
            except BaseException:
                if process.poll() is None:
                    os.killpg(process.pid, signal.SIGTERM)
                    try:
                        process.wait(timeout=10)
                    except subprocess.TimeoutExpired:
                        os.killpg(process.pid, signal.SIGKILL)
                        process.wait()
                raise
        require(code == 0, f"{name} failed (exit {code}). See {path}")


def preflight(runner, glass):
    require(sys.platform == "darwin", "The build/setup must run on your Mac. --dry-run works without Xcode.")
    for name in ("git", "zsh", "xcodebuild", "xcrun", "glass", "mint"):
        require(shutil.which(name, path=runner.env.get("PATH")), f"Required command is missing: {name}")
    output = runner.capture(["xcodebuild", "-version"])
    print(output)
    match = re.search(r"Xcode (\d+)\.(\d+)", output)
    required = str(plistlib.loads((glass / "Glass.plist").read_bytes()).get("XCODE_VERSION", ""))
    require(match and re.match(r"^\d+\.\d+", required), "Could not read Xcode versions.")
    require(tuple(map(int, match.groups())) == tuple(map(int, required.split(".")[:2])),
            f"Glass requires Xcode {required}. Select that Xcode, or pass --xcode /path/to/Xcode.app.")
    for sdk in ("iphoneos", "iphonesimulator"):
        location = runner.capture(["xcrun", "--sdk", sdk, "--show-sdk-path"])
        require(Path(location).is_dir(), f"Xcode's {sdk} SDK is missing: {location}")
    runner.capture(["xcodebuild", "-checkFirstLaunchStatus"])
    branch = runner.capture(["git", "branch", "--show-current"], cwd=glass)
    print(f"Glass branch: {branch or '(detached HEAD)'}")
    print("Using this checkout as-is; no branch switches, commits, or pushes.")


class RunFiles:
    def __init__(self, root, version, paths, sdk, glass, zxing_url):
        self.root = root
        self.manifest_path = root / "run.json"
        (root / "backups").mkdir(parents=True)
        (root / "logs").mkdir()
        (root / "artifacts").mkdir()
        self.data = {"format": 1, "status": "backed-up", "version": version,
                     "sdk": str(sdk), "glass": str(glass), "zxing_url": zxing_url, "files": []}
        for index, path in enumerate(paths):
            require(path.is_file() and not path.is_symlink(), f"Expected a regular file: {path}")
            backup = root / "backups" / f"{index}-{path.name}"
            shutil.copy2(path, backup)
            self.data["files"].append({"path": str(path), "backup": str(backup.relative_to(root)),
                                       "before": sha(backup), "after": sha(backup),
                                       "mode": path.stat().st_mode & 0o777})
        self.save()

    def save(self):
        atomic_write(self.manifest_path, json_bytes(self.data))

    def status(self, value):
        self.data["status"] = value
        self.save()

    def write(self, path, content):
        record = next(item for item in self.data["files"] if item["path"] == str(path))
        require(sha(path) == record["after"], f"File changed during setup; not overwriting it: {path}")
        record["after"] = hashlib.sha256(content).hexdigest()
        self.save()  # Record the intended write before replacing the file, for interruption recovery.
        atomic_write(path, content, record["mode"])


def restore_files(root):
    root = root.expanduser().resolve()
    manifest = read_json(root / "run.json")
    require(manifest.get("format") == 1, "Unrecognized backup manifest.")
    records = manifest["files"]
    require(len(records) == 4, "Expected four backed-up files.")
    for item in records:
        target = Path(item["path"])
        backup = (root / item["backup"]).resolve()
        require(root in backup.parents and backup.is_file(), "Backup file is missing or outside this run folder.")
        require(sha(backup) == item["before"], f"Backup contents changed: {backup}")
        require(target.is_file() and not target.is_symlink(), f"Cannot safely restore {target}")
        require(sha(target) in (item["before"], item["after"]),
                f"{target} was edited after setup. Restore it manually from {backup}; no files were restored.")
    for item in records:
        atomic_write(Path(item["path"]), (root / item["backup"]).read_bytes(), item["mode"])
    manifest["status"] = "files-restored"
    atomic_write(root / "run.json", json_bytes(manifest))
    print("Restored the four backed-up source/config files. Artifacts and logs were kept.")
    print("This does not undo Glass setup's dependencies, generated files, Git hooks, or caches.")


def device_library(framework):
    info = plistlib.loads((framework / "Info.plist").read_bytes())
    matches = [lib for lib in info.get("AvailableLibraries", [])
               if lib.get("SupportedPlatform") == "ios" and not lib.get("SupportedPlatformVariant")
               and "arm64" in lib.get("SupportedArchitectures", [])]
    require(len(matches) == 1, f"Expected one arm64 iPhone library in {framework}")
    return matches[0]


def inside(root, relative):
    result = (root / relative).resolve()
    require(root.resolve() in result.parents, f"Invalid bundle path: {relative}")
    return result


def binary_in(framework, lib):
    bundle = inside(framework, lib["LibraryIdentifier"] + "/" + lib["LibraryPath"])
    # ZXing ships a static .a library in its XCFramework, not an inner .framework.
    if bundle.is_file():
        return bundle
    info = plistlib.loads((bundle / "Info.plist").read_bytes())
    executable = inside(bundle, info["CFBundleExecutable"])
    require(executable.is_file(), f"Missing binary: {executable}")
    return executable


def validate_osiris(framework):
    info = plistlib.loads((framework / "Info.plist").read_bytes())
    libs = info.get("AvailableLibraries", [])
    device_library(framework)
    require(any(lib.get("SupportedPlatformVariant") == "simulator" for lib in libs),
            "OsirisKit simulator slice is missing.")
    for lib in libs:
        binary_in(framework, lib)
        bundle = inside(framework, lib["LibraryIdentifier"] + "/" + lib["LibraryPath"])
        for module in MODULES:
            require((bundle / "Modules" / (module + ".swiftmodule")).is_dir(), f"Missing Swift module: {module}")
            header = bundle / "Headers" / (module + "-Swift.h")
            require(header.is_file() and "Generated by Apple Swift version" in header.read_text(),
                    f"Missing compiler-generated header: {header}")


def compare_device_binary(expected, installed):
    require(installed.is_dir(), f"Framework was not installed: {installed}")
    require(sha(binary_in(expected, device_library(expected))) == sha(binary_in(installed, device_library(installed))),
            f"Installed {installed.name} differs from the SDK build. Stopped instead of reporting a stale package as ready.")


def compare_osiris_headers(expected, installed):
    roots = []
    for framework in (expected, installed):
        lib = device_library(framework)
        roots.append(inside(framework, lib["LibraryIdentifier"] + "/" + lib["LibraryPath"]))
    for module in MODULES:
        name = module + "-Swift.h"
        require(sha(roots[0] / "Headers" / name) == sha(roots[1] / "Headers" / name),
                f"Installed OsirisKit header differs from the SDK build: {name}")


def find_built_zxing(sdk):
    artifacts = sdk / "build-xcframework/ios-arm64/DerivedData/SourcePackages/artifacts"
    matches = [p for p in artifacts.rglob("*.xcframework") if p.name.lower() == "zxingcpp.xcframework"]
    require(len(matches) == 1, f"Expected one ZXingCPP XCFramework from the successful SDK build, found {len(matches)} under {artifacts}.")
    return matches[0]


def prepare(args):
    parent = Path(__file__).resolve().parent
    sdk = discover(parent, args.sdk, sdk_root, "sdk")
    glass = discover(parent, args.glass, glass_root, "glass")
    require(sdk != glass, "SDK and Glass must be different folders.")
    paths = [sdk / SCRIPT_REL, glass / OSIRIS_JSON, glass / ZXING_JSON, glass / LOCK_REL]
    for path in paths:
        require(not path.is_symlink(), f"Config files must not be symlinks: {path}")
    snapshots = {path: path.read_bytes() for path in paths}
    package_before = sha(sdk / "Package.swift")
    patched = patch_script(snapshots[paths[0]].decode())
    zxing_url, zxing_checksum = zxing_spec(sdk)
    osiris_map, zxing_map = (json.loads(snapshots[path]) for path in paths[1:3])
    require(isinstance(osiris_map, dict) and isinstance(zxing_map, dict), "Dependency JSON files must contain objects.")
    # Three numeric components, with a fresh local key to bypass Glass's version-only cache.
    number = int(time.time())
    while f"0.0.{number}" in osiris_map or f"0.0.{number}" in zxing_map:
        number += 1
    version = f"0.0.{number}"
    lock = change_lock(snapshots[paths[3]].decode(), version)
    print(f"SDK: {sdk}\nGlass: {glass}\nLocal test key: {version}\nMatching ZXing: {zxing_url}")
    print("Will back up four files, patch packaging, build, validate, configure dependencies, then run Glass setup.")
    if args.dry_run:
        print("DRY RUN: no files changed, commands run, or dependencies downloaded.")
        return

    env = os.environ.copy()
    if args.xcode:
        developer = args.xcode.expanduser().resolve() / "Contents/Developer"
        require(developer.is_dir(), f"Not an Xcode app: {args.xcode}")
        env["DEVELOPER_DIR"] = str(developer)
    runner = Runner(env)
    preflight(runner, glass)

    state_root = parent / STATE_DIR
    state_root.mkdir(exist_ok=True)
    # Prevent two invocations from modifying the same build and dependency files concurrently.
    import fcntl
    with (state_root / "setup.lock").open("a") as lock_file:
        try:
            fcntl.flock(lock_file, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError as exc:
            raise SetupError("Another copy of this setup script is already running here.") from exc
        for path, content in snapshots.items():
            require(path.read_bytes() == content, f"File changed while checking prerequisites; rerun to use the latest contents: {path}")
        require(sha(sdk / "Package.swift") == package_before,
                "Package.swift changed while checking prerequisites. Rerun to use the latest dependency.")
        run_name = dt.datetime.now().strftime("%Y%m%d-%H%M%S") + "-" + uuid.uuid4().hex[:8]
        files = RunFiles(state_root / run_name, version, paths, sdk, glass, zxing_url)
        runner.logs = files.root / "logs"
        print(f"\nBackups and logs: {files.root}", flush=True)
        try:
            files.write(paths[0], patched.encode())
            files.status("building-sdk")
            runner.stream(["zsh", str(paths[0]), version], sdk, "sdk-build")
            require(sha(sdk / "Package.swift") == package_before,
                    "Package.swift changed during the SDK build. Rerun with a stable checkout.")
            built = sdk / "build-xcframework/OsirisKit.xcframework"
            validate_osiris(built)
            source_zip = sdk / "build-xcframework" / f"xcframework-iOS-OsirisKit-{version}.zip"
            require(source_zip.is_file(), f"SDK did not produce its ZIP: {source_zip}")
            with zipfile.ZipFile(source_zip) as archive:
                require(archive.testzip() is None, "The generated OsirisKit ZIP is corrupt.")
                require(any(name.endswith("/Headers/Osiris-Swift.h") for name in archive.namelist()),
                        "The generated ZIP does not include the new headers.")
            zxing_built = find_built_zxing(sdk)
            # Keep this immutable input outside build-xcframework, which the next build deletes.
            durable_zip = files.root / "artifacts" / source_zip.name
            shutil.copy2(source_zip, durable_zip)
            files.data["artifact_sha256"] = sha(durable_zip)
            files.data["zxing_expected_checksum"] = zxing_checksum
            files.save()

            osiris_map[version] = durable_zip.as_uri()
            zxing_map[version] = zxing_url
            files.write(paths[1], json_bytes(osiris_map))
            files.write(paths[2], json_bytes(zxing_map))
            files.write(paths[3], lock.encode())
            files.status("installing-glass-dependencies")
            runner.stream(["glass", "environment", "setup", "-v"], glass, "glass-setup")

            installed = glass / "Carthage/Build"
            validate_osiris(installed / "OsirisKit.xcframework")
            compare_device_binary(built, installed / "OsirisKit.xcframework")
            compare_osiris_headers(built, installed / "OsirisKit.xcframework")
            compare_device_binary(zxing_built, installed / "ZXingCPP.xcframework")
            files.status("ready-for-xcode-test")
            print("\nREADY FOR XCODE TEST: SDK build and Glass dependency setup passed.")
            print("The installed iPhone binaries match the SDK build. Phone scanning is not tested yet.")
            print(f"Open {glass / 'Plugins/Scanner/Scanner.xcodeproj'}")
            print("Select ScannerApp and your iPhone, clean the build folder, then Run.")
            print("Triple-tap the camera preview and choose Osiris in the debug menu.")
            print(f"Keep this folder while using the local test dependency: {files.root}")
        except BaseException:
            files.status("stopped-before-completion")
            print(f"\nStopped. Backups, partial outputs, and logs were kept in: {files.root}", file=sys.stderr)
            print("To restore only the four source/config files:\n" +
                  shlex.join([sys.executable, str(Path(__file__).resolve()), "--restore", str(files.root)]), file=sys.stderr)
            raise


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--sdk", type=Path, help="Explicit osiris-ios root, if not a unique sibling folder")
    parser.add_argument("--glass", type=Path, help="Explicit glass-app root, if not a unique sibling folder")
    parser.add_argument("--xcode", type=Path, help="Use this Xcode.app for this run; does not change xcode-select")
    parser.add_argument("--dry-run", action="store_true", help="Validate repo/config shapes and show the plan only")
    parser.add_argument("--restore", type=Path, metavar="RUN_FOLDER", help="Restore the four backed-up files, preserving later manual edits")
    args = parser.parse_args()
    try:
        require(sys.version_info >= (3, 9), "Python 3.9 or newer is required.")
        if args.restore:
            require(not (args.dry_run or args.sdk or args.glass or args.xcode), "Use --restore by itself.")
            restore_files(args.restore)
        else:
            prepare(args)
        return 0
    except KeyboardInterrupt:
        print("\nCancelled. No commit, push, or publication was performed.", file=sys.stderr)
        return 130
    except (SetupError, OSError, ValueError, KeyError, zipfile.BadZipFile, plistlib.InvalidFileException) as exc:
        print(f"\nERROR: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
